-- アプリ側で資本金のしきい値を判定する。
UPDATE procedures
SET
  include_in_diagnosis = TRUE,
  description = '消費税の課税事業者が、課税期間中の課税売上・仕入れに基づいて行う確定申告です。新設法人でも資本金または出資金が1,000万円以上の場合は、設立期から課税事業者になります。',
  caution_note = '資本金1,000万円未満でも、インボイス登録、課税事業者選択、特定新規設立法人などにより申告が必要な場合があります。'
WHERE code = 'CONSUMPTION_TAX_RETURN';
